#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "bytecode/bytecode.h"
#include "common/xalloc.h"
#include "qcc.h"

static void print_usage(const char* program) {
    printf("Qora compiler (QCC) %s\n\n", QCC_VERSION);
    printf("usage: %s <file.q>\n\n", program);
    printf("options:\n");
    printf("  -h, --help     show this help\n");
    printf("      --version  show version\n\n");
    printf("Compiles a Qora source file (.q) and prints the generated bytecode.\n");
    printf("Exit code is 1 if the file contains errors.\n");
}

static char* read_file(const char* path) {
    FILE* file = fopen(path, "rb");
    if (!file) return NULL;

    if (fseek(file, 0, SEEK_END) != 0) {
        fclose(file);
        return NULL;
    }

    long size = ftell(file);
    if (size < 0) {
        fclose(file);
        return NULL;
    }
    rewind(file);

    char* buffer = xmalloc((size_t)size + 1);
    size_t read = fread(buffer, 1, (size_t)size, file);
    buffer[read] = '\0';

    fclose(file);
    return buffer;
}

int main(int argc, char** argv) {
    if (argc < 2) {
        print_usage(argv[0]);
        return 2;
    }

    if (strcmp(argv[1], "-h") == 0 || strcmp(argv[1], "--help") == 0) {
        print_usage(argv[0]);
        return 0;
    }

    if (strcmp(argv[1], "--version") == 0) {
        printf("qcc %s\n", QCC_VERSION);
        return 0;
    }

    const char* path = argv[1];
    char* source = read_file(path);
    if (!source) {
        fprintf(stderr, "error: cannot read file '%s'\n", path);
        return 1;
    }

    Bytecode* bc = qcc_compile(source);
    free(source);

    if (!bc) return 1;

    bytecode_dump(bc);
    bytecode_free(bc);
    return 0;
}
